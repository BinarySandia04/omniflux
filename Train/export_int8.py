#!/usr/bin/env python3
"""Export the int8 TFLite model to a C header the firmware runs without TFLM.

Reads model_int8.tflite (full-integer: int8 in/out) and writes
../Frimware/src/model_int8_weights.h with, per dense layer:
  - int8 weights (row-major, o * in + i) and int32 biases
  - per-neuron quantized multiplier/shift to requantize the int32 accumulator
  - per-tensor activation scale/zero-point

The firmware multiplies int8 x int8 into int32, requantizes with the multipliers
(same maths as TFLite's reference kernel) and applies relu between layers.

Run from the Train/ directory, after the notebook regenerated the .tflite:

    python export_int8.py
"""
import numpy as np
from tensorflow.lite.python import schema_py_generated as schema

SRC = "model_int8.tflite"
OUT = "../Frimware/src/model_int8_weights.h"

FULLY_CONNECTED = 9


def quantize_multiplier(real):
    """Same as TFLite's QuantizeMultiplier: real = mult * 2^shift, mult in [0.5, 1)."""
    if real == 0:
        return 0, 0
    mantissa, shift = np.frexp(real)
    q = int(round(float(mantissa) * (1 << 31)))
    if q == (1 << 31):
        q //= 2
        shift += 1
    return q, int(shift)




def main():
    buf = open(SRC, "rb").read()
    model = schema.Model.GetRootAsModel(buf, 0)
    sg = model.Subgraphs(0)

    def quant(t):
        q = t.Quantization()
        scales = [q.Scale(i) for i in range(q.ScaleLength())]
        zero = [q.ZeroPoint(i) for i in range(q.ZeroPointLength())]
        return scales, zero

    def buf_bytes(t):
        b = model.Buffers(t.Buffer())
        return bytes(b.Data(k) for k in range(b.DataLength()))

    def raw(t):
        return np.frombuffer(buf_bytes(t), dtype=np.int8)

    def raw_i32(t):
        return np.frombuffer(buf_bytes(t), dtype=np.int32)

    fc_ops = [sg.Operators(i) for i in range(sg.OperatorsLength())
              if model.OperatorCodes(sg.Operators(i).OpcodeIndex()).BuiltinCode() == FULLY_CONNECTED]

    layers = []
    for idx, op in enumerate(fc_ops):
        t_in = sg.Tensors(op.Inputs(0))
        t_w = sg.Tensors(op.Inputs(1))
        t_b = sg.Tensors(op.Inputs(2))
        t_out = sg.Tensors(op.Outputs(0))

        in_scale, in_zero = quant(t_in)
        out_scale, out_zero = quant(t_out)
        w_scale, w_zero = quant(t_w)

        assert w_zero[0] == 0, "weights must be symmetric"
        assert t_w.Shape(1) == t_in.Shape(1) and t_w.Shape(0) == t_out.Shape(1), "shape mismatch"

        n_out, n_in = int(t_w.Shape(0)), int(t_w.Shape(1))
        W = raw(t_w).reshape(n_out, n_in)
        b = raw_i32(t_b)

        # One multiplier per output neuron when the weights are per-axis (dim 0).
        mults, shifts = [], []
        for o in range(n_out):
            ws = w_scale[o] if len(w_scale) > 1 else w_scale[0]
            m, s = quantize_multiplier(in_scale[0] * ws / out_scale[0])
            mults.append(m)
            shifts.append(s)

        layers.append(dict(
            W=W, b=b, mult=mults, shift=shifts,
            in_scale=in_scale[0], in_zero=in_zero[0],
            out_scale=out_scale[0], out_zero=out_zero[0],
            relu=(idx != len(fc_ops) - 1),
        ))

    arch = [int(sg.Tensors(sg.Operators(0).Inputs(0)).Shape(1))]
    arch += [l["W"].shape[0] for l in layers]
    in_scale, in_zero = quant(sg.Tensors(sg.Inputs(0)))

    out = [
        "#pragma once",
        "#include <stdint.h>",
        "",
        "// AUTO-GENERATED by Train/export_int8.py from %s" % SRC,
        "// %s, relu hidden + sigmoid output, int8." % " -> ".join(map(str, arch)),
        "",
        "#define MODEL_IN_DIM %d" % arch[0],
        "#define NUM_DENSE %d" % len(layers),
        "#define MAX_UNITS %d" % max(arch[1:]),
        "",
        "#define IN_SCALE %.9gf" % in_scale[0],
        "#define IN_ZERO  %d" % in_zero[0],
        "",
    ]

    def carr(ctype, name, arr, per=12):
        a = np.asarray(arr).ravel()
        lines = ["const %s %s[%d] = {" % (ctype, name, a.size)]
        for i in range(0, a.size, per):
            lines.append("    " + ", ".join(str(int(v)) for v in a[i:i + per]) + ",")
        lines.append("};")
        return "\n".join(lines)

    def farr(name, arr, per=6):
        a = np.asarray(arr, np.float32).ravel()
        lines = ["const float %s[%d] = {" % (name, a.size)]
        for i in range(0, a.size, per):
            lines.append("    " + ", ".join("%.9gf" % v for v in a[i:i + per]) + ",")
        lines.append("};")
        return "\n".join(lines)

    for i, l in enumerate(layers):
        out += ["// %d -> %d%s" % (arch[i], arch[i + 1], " (relu)" if l["relu"] else ""),
                carr("int8_t", "g_W%d" % i, l["W"]),
                carr("int32_t", "g_b%d" % i, l["b"]),
                carr("int32_t", "g_mult%d" % i, l["mult"], per=4),
                carr("int8_t", "g_shift%d" % i, l["shift"], per=12),
                farr("g_out_scale%d" % i, [l["out_scale"]]),
                "", ]

    out += [
        "const unsigned short g_in_dim[NUM_DENSE]  = {%s};" % ", ".join(map(str, arch[:-1])),
        "const unsigned short g_out_dim[NUM_DENSE] = {%s};" % ", ".join(map(str, arch[1:])),
        "const int8_t  *const g_W[NUM_DENSE]    = {%s};" % ", ".join("g_W%d" % i for i in range(len(layers))),
        "const int32_t *const g_b[NUM_DENSE]    = {%s};" % ", ".join("g_b%d" % i for i in range(len(layers))),
        "const int32_t *const g_mult[NUM_DENSE] = {%s};" % ", ".join("g_mult%d" % i for i in range(len(layers))),
        "const int8_t  *const g_shift[NUM_DENSE]= {%s};" % ", ".join("g_shift%d" % i for i in range(len(layers))),
        "const float   *const g_oscale[NUM_DENSE] = {%s};" % ", ".join("g_out_scale%d" % i for i in range(len(layers))),
        "const int16_t g_ozero[NUM_DENSE] = {%s};" % ", ".join(str(l["out_zero"]) for l in layers),
        "const unsigned char g_relu[NUM_DENSE] = {%s};" % ", ".join("1" if l["relu"] else "0" for l in layers),
        "",
    ]

    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print("Wrote %s (%s)" % (OUT, " -> ".join(map(str, arch))))


if __name__ == "__main__":
    main()
