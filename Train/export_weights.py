#!/usr/bin/env python3
"""Export the trained Keras model to a C header the firmware runs directly.

Dense layers + relu, single sigmoid output (wrist extension / flexion).

Run from the Train/ directory, after the notebook regenerated the .tflite:

    python export_weights.py

Reads model_float32.tflite and writes ../Frimware/src/model_weights.h with
  - g_W0/g_b0, g_W1/g_b1, ... (row-major: g_W0[o * in + i])
  - g_in_dim[] / g_out_dim[] / g_W[] / g_b[]
  - MODEL_IN_DIM, NUM_DENSE, MAX_UNITS
"""
import numpy as np
import tensorflow as tf

SRC = "model_float32.tflite"
OUT = "../Frimware/src/model_weights.h"


def dense_layers(interp):
    """(W, b) per FULLY_CONNECTED op, in graph order."""
    layers = []
    for op in interp._get_ops_details():
        if op["op_name"] != "FULLY_CONNECTED":
            continue
        w = interp.get_tensor(op["inputs"][1])
        b = interp.get_tensor(op["inputs"][2]).ravel()
        assert w.ndim == 2 and b.shape[0] == w.shape[0], "unexpected dense shapes"
        layers.append((w, b))
    return layers


def carr(name, arr, per=6):
    a = np.asarray(arr, np.float32).ravel()
    lines = ["const float %s[%d] = {" % (name, a.size)]
    for i in range(0, a.size, per):
        lines.append("    " + ", ".join("%.9g" % v for v in a[i:i + per]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    interp = tf.lite.Interpreter(model_path=SRC)
    interp.allocate_tensors()
    layers = dense_layers(interp)
    arch = [layers[0][0].shape[1]] + [w.shape[0] for w, _ in layers]

    out = [
        "#pragma once",
        "",
        "// AUTO-GENERATED by Train/export_weights.py from %s" % SRC,
        "// %s, sigmoid output." % " -> ".join(map(str, arch)),
        "// Dense weights are row-major: g_W0[o * %d + i], g_W1[o * %d + i], ..." % (arch[0], arch[1]),
        "",
        "#define MODEL_IN_DIM %d" % arch[0],
        "#define NUM_DENSE %d" % len(layers),
        "#define MAX_UNITS %d" % max(arch[1:]),
        "",
    ]
    for i, (w, b) in enumerate(layers):
        out.append("// %d -> %d" % (arch[i], arch[i + 1]))
        out.append(carr("g_W%d" % i, w))
        out.append(carr("g_b%d" % i, b))
        out.append("")
    out += [
        "const unsigned short g_in_dim[NUM_DENSE]  = {%s};" % ", ".join(map(str, arch[:-1])),
        "const unsigned short g_out_dim[NUM_DENSE] = {%s};" % ", ".join(map(str, arch[1:])),
        "const float *const g_W[NUM_DENSE] = {%s};" % ", ".join("g_W%d" % i for i in range(len(layers))),
        "const float *const g_b[NUM_DENSE] = {%s};" % ", ".join("g_b%d" % i for i in range(len(layers))),
        "",
    ]

    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print("Wrote %s (%s)" % (OUT, " -> ".join(map(str, arch))))


if __name__ == "__main__":
    main()
