#!/usr/bin/env python3
"""Export ONLY the StandardScaler + gesture labels as a minimal C header.

Unlike export_model.py (which also dumps the old hand-rolled model weights),
this emits just what the TFLite Micro firmware needs to preprocess the raw
IMU window: g_mean[], g_scale[], INPUT_DIM, NUM_CLASSES, GESTURE_CLASSES[].

Run from the Train/ directory:
    python export_scaler.py
"""
import os
import numpy as np

OUT_HEADER = "../Frimware/src/scaler.h"
CAPTURES = "../dataset/captures"


def carr(name, arr):
    lines = []
    for i in range(0, len(arr), 6):
        lines.append("    " + ", ".join("%.9gf" % float(v) for v in arr[i:i + 6]) + ",")
    return "const float %s[%d] = {\n%s\n};\n" % (name, len(arr), "\n".join(lines))


def main():
    d = np.load("scaler.npz")
    assert "mean" in d and "scale" in d, "scaler.npz must have 'mean' and 'scale'"
    mean = np.asarray(d["mean"], np.float32).ravel()
    scale = np.asarray(d["scale"], np.float32).ravel()
    n = mean.size

    # must match Train_model.ipynb: 0 = extension, 1 = flexion
    classes = ["label_WRIST_EXTENSION", "label_WRIST_FLEXION"]

    out = [
        "// AUTO-GENERATED by Train/export_scaler.py — do not edit by hand.",
        "#pragma once",
        "",
        "#define INPUT_DIM   %d" % n,
        "#define NUM_CLASSES %d" % len(classes),
        "",
        carr("g_mean", mean),
        carr("g_scale", scale),
        "",
        "const char* const GESTURE_CLASSES[NUM_CLASSES] = {",
    ]
    for c in classes:
        out.append('    "%s",' % (c[6:] if c.startswith("label_") else c))
    out.append("};")

    os.makedirs(os.path.dirname(OUT_HEADER), exist_ok=True)
    with open(OUT_HEADER, "w") as f:
        f.write("\n".join(out) + "\n")
    print("Wrote %s (%d features, %d classes)" % (OUT_HEADER, n, len(classes)))


if __name__ == "__main__":
    main()
